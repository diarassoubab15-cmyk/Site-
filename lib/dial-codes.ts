/** Pays principal d'un indicatif partagé (+1 → États-Unis, +7 → Russie, +44 → Royaume-Uni…). */
const MAIN = ["US", "RU", "GB", "NO", "AU", "RE", "GP", "FI", "CW", "SH", "IT"];

export const flag = (iso: string) => String.fromCodePoint(...[...iso.toUpperCase()].map((c) => 0x1f1a5 + c.charCodeAt(0)));

/** Indicatif reconnu au début d'un numéro (« +223 70… » → Mali). Le plus long l'emporte (+1 268 avant +1). */
export function splitPhone(value: string, fallbackIso = "ML"): { iso: string; rest: string } {
  const v = value.trim();
  if (v.startsWith("+")) {
    const digits = v.slice(1).replace(/\D/g, "");
    const rank = (iso: string) => (MOBILE_MONEY[iso] ? 2 : MAIN.includes(iso) ? 1 : 0);
    const hits = DIAL_COUNTRIES.filter((c) => digits.startsWith(c.code)).sort((a, b) => b.code.length - a.code.length || rank(b.iso) - rank(a.iso));
    if (hits.length) {
      const after = v.slice(1).replace(/^\s*/, "");
      let n = 0, i = 0;
      while (i < after.length && n < hits[0].code.length) { if (/\d/.test(after[i])) n++; i++; }
      return { iso: hits[0].iso, rest: after.slice(i).trim() };
    }
  }
  return { iso: fallbackIso, rest: v };
}
